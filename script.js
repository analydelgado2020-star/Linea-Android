let current = 0;
let waiting = false;

const path = document.getElementById("trackPath");
const car = document.getElementById("car");

function goToTimeline(){

    resetGame(); // 🔥 REINICIA TODO PRIMERO

    document.getElementById("screen1").classList.remove("active");
    document.getElementById("screen2").classList.add("active");

}

function goToEnd(){
    document.getElementById("screen2").classList.remove("active");
    document.getElementById("screen3").classList.add("active");
}

function restart(){
    document.getElementById("screen3").classList.remove("active");
    document.getElementById("screen1").classList.add("active");

    current = 0;
    moveCar(0);
}

function moveCar(progress){
    const length = path.getTotalLength();
    const point = path.getPointAtLength(progress * length);
    car.style.left = point.x + "px";
    car.style.top = point.y + "px";
}

function updateButtons(){
    const backBtn = document.getElementById("backBtn");
    const nextBtn = document.getElementById("nextBtn");
    const finishBtn = document.getElementById("finishBtn");

    backBtn.style.display = current === 0 ? "none" : "inline-block";

    if(current === data.length - 1){
        nextBtn.style.display = "none";
        finishBtn.style.display = "inline-block";
    } else {
        nextBtn.style.display = "inline-block";
        finishBtn.style.display = "none";
    }
}

function loadStation(){

    let progress = current / (data.length - 1);
    moveCar(progress);

    document.getElementById("title").innerText = data[current].title;
    document.getElementById("description").innerHTML = data[current].desc;
    document.getElementById("extraImage").src = data[current].img;
    document.getElementById("infoBox").style.display = "block";

    waiting = true;

    // Ocultar botones mientras espera
    document.getElementById("backBtn").style.display = "none";
    document.getElementById("nextBtn").style.display = "none";
    document.getElementById("finishBtn").style.display = "none";

    setTimeout(()=>{
        waiting = false;
        updateButtons();
    },2000); // aquí cambias el tiempo
}

function playAuto(){
    document.getElementById("playBtn").style.display = "none";
    current = 0;
    loadStation();
}

function nextStop(){
    if(waiting) return;

    if(current < data.length -1){
        current++;
        loadStation();
    }
}

function previousStop(){
    if(waiting) return;

    if(current > 0){
        current--;
        loadStation();
    }
}
function restart(){

    document.getElementById("screen3").classList.remove("active");
    document.getElementById("screen1").classList.add("active");

    resetGame(); // 🔥 REINICIO COMPLETO
}
function resetGame(){

    current = 0;
    waiting = false;

    moveCar(0);

    // Ocultar info
    document.getElementById("infoBox").style.display = "none";

    // Mostrar botón Play otra vez
    document.getElementById("playBtn").style.display = "inline-block";

    // Ocultar botones de navegación
    document.getElementById("backBtn").style.display = "none";
    document.getElementById("nextBtn").style.display = "none";
    document.getElementById("finishBtn").style.display = "none";
}